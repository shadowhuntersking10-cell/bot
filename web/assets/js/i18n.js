let current = null;
export function getLang() {
  if (current) return current;
  let l = null;
  try { l = localStorage.getItem(KEY); } catch (e) { /* */ }
  current = LANGS.includes(l) ? l : "uz";
  return current;
}
export function setLang(lang) {
  current = LANGS.includes(lang) ? lang : "uz";
  try { localStorage.setItem(KEY, current); } catch (e) { /* */ }
}
function pick(entry) {
  const i = LANGS.indexOf(getLang());
  return entry[i] || entry[1] || entry[0];
}
export function t(key, params) {
  const entry = D[key];
  let s = entry ? pick(entry) : key.replace(/^(st_|tx_|s_|f_|a_)/, "").replace(/_/g, " ");
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
/** Map a server `detail` (string code, "code:extra", or {code}) to text. */
export function errorText(detail) {
  let code = detail;
  if (detail && typeof detail === "object") code = detail.code || "error";
  code = String(code || "error");
  const base = code.split(":")[0];
  if (E[code]) return pick(E[code]);
  if (E[base]) return pick(E[base]) + (code.includes(":") ? ` (${code.split(":").slice(1).join(":")})` : "");
  if (/^[a-z0-9_]+$/.test(code)) return pick(E.error) + ` (${code})`;
  return code.slice(0, 200); // human-readable message from the server (e.g. supplier error)
}
